"""Controlled ``cov_*`` participant-covariate vocabulary, alias resolution, and
the non-substantive-column exclusion used by ``Scripts/build_sdt_participant.py``.

Why this module exists
----------------------
The participant-level moderator panel is built from ``temp/sdt_participant_specs.csv``,
which ``build_sdt_participant.py`` derives from the per-study harmonized covariate
vocabulary (``Datasets/<Key>/<Key> - harmonized_variables.csv``, rows whose
``uniform_variable`` starts with ``cov_``).  That vocabulary is highly fragmented:
the same construct is coded under many names across datasets (e.g. age as
``cov_age`` / ``cov_age_recoded`` / ``cov_age_18_24`` / ``cov_birth_year``;
ideology as ``cov_politics`` / ``cov_ideology`` / ``cov_political_ideology_*`` ...),
raw units differ across datasets, and non-substantive columns (attention checks,
completion time, survey weights, condition/arm codes, order/counterbalance,
bookkeeping) are mixed in.

This module fixes the *naming* problem at analysis time, in the style of
``Scripts/domain_restriction.py`` for ``dv_domain``: it is a single documented
mapping that ``build_sdt_participant.py`` applies, so every regeneration of
``temp/sdt_participant_specs.csv`` resolves the same aliases to the same canonical
covariate and drops the same non-substantive columns.  Existing sidecars
(``harmonized_variables.csv``) are **never** rewritten; ``harmonizer_template.py``
carries the same vocabulary so *future* harmonisations emit canonical names.

Observed vocabulary (2026-09-20)
--------------------------------
Reading every ``Datasets/*/* - harmonized_variables.csv`` and stripping the
``_i<n>`` item-set suffix gives **652** distinct ``cov_*`` base names (a
comparable count over the wide CSVs is 662; the earlier estimate of 245 in
``PARTICIPANT_MODERATORS_ASSESSMENT.md`` did not reproduce under any of the
sidecar/wide/`_01` counting variants).  ``_OBSERVED_COV_NAMES`` below is the
snapshot this mapping was derived from; ``COV_ALIASES`` is materialised from it.

Resolution rules (applied in order)
-----------------------------------
1. ``is_excluded_cov`` matches a ``COV_EXCLUDE`` pattern -> the column is dropped
   (not a substantive participant moderator).
2. A name equal to a canonical passes through (``COV_CANONICAL``).
3. A name in ``COV_ALIASES`` resolves to its canonical (materialised from the
   observed snapshot by the rules below).
4. Otherwise the ordered ``COV_ALIAS_RULES`` are applied (first match wins).
5. Anything still unresolved returns ``None`` and is **dropped and reported**
   (it is not part of the controlled vocabulary).

The dropped-but-unresolved names are all mentioned by <5 studies, so they would
fail the app's ``MIN_PARTICIPANT_STUDIES = 5`` filter anyway; the mapping only
matters for constructs that can reach the panel.  Use the ``__main__`` self-check
to list them.

Units policy
------------
Raw covariate units are inconsistent across datasets -- ``cov_age`` is years in
some datasets, a z-score in others and a birth year in others (observed levels
include ``15``, ``0.204``, ``-0.47``, ``1.98e+03``).  Continuous participant
moderators are therefore analysed on the harmonizer's **within-study 0-1
rescale** (``<name>_01``); the raw-unit column is never pooled.  ``cov_birth_year``
is an age alias whose 0-1 rescale runs the opposite way, so ``is_reversed_cov``
flags it and the analysis layer flips it (``1 - value``) to match ``cov_age``
(higher = older).

Choices and ambiguities are recorded in ``Scripts/COVARIATE_VOCABULARY.md``.
"""

