_COV_EXCLUDE_RX = [re.compile(p, re.I) for p in COV_EXCLUDE]
_COV_ALIAS_RX = [(re.compile(p, re.I), c) for p, c in COV_ALIAS_RULES]


def is_excluded_cov(name):
    """True if ``name`` is a non-substantive column that must be dropped."""
    n = str(name or "").strip()
    if not n:
        return False
    return any(rx.search(n) for rx in _COV_EXCLUDE_RX)


def is_reversed_cov(name):
    """True if the 0-1 rescale of ``name`` runs opposite to its canonical."""
    n = str(name or "").strip()
    return any(n == k or n.startswith(k + "_") for k in _REVERSED_ALIASES)


def _resolve(name):
    n = str(name or "").strip()
    if not n:
        return None
    if is_excluded_cov(n):
        return None
    if n in COV_CANONICAL:
        return n
    for rx, c in _COV_ALIAS_RX:
        if rx.search(n):
            return c
    return None


# {raw cov name -> canonical} for every observed name that resolves.
COV_ALIASES = {n: c for n in _OBSERVED_COV_NAMES if (c := _resolve(n))}


def canonical_cov(name):
    """Return the canonical ``cov_*`` name for ``name``, or ``None``.

    ``None`` means the column is either non-substantive (``is_excluded_cov``) or
    outside the controlled vocabulary; the caller drops it.  Names already in
    ``COV_ALIASES`` return the recorded canonical, so the observed snapshot and
    the live rules cannot drift.
    """
    n = str(name or "").strip()
    if not n:
        return None
    if n in COV_ALIASES:
        return COV_ALIASES[n]
    return _resolve(n)


