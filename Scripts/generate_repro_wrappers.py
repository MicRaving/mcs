"""Generate thin reproduction-script wrappers for the study datasets.

Each ``Datasets/<Key>/<Key> - reproduction.py`` is a thin wrapper around the
shared engine ``Scripts/repro_lib.py::reproduce(KEY)``.  This script (re)creates
those wrappers so a dataset that lacks one (or whose wrapper was deleted) can be
picked up by ``Scripts/analysis/run_reproducers.py`` again.

Usage:
    python Scripts/generate_repro_wrappers.py [--root ROOT] [--only SUBSTR]
                                              [--force] [--sb] [--dry-run]

  --root    the project root (default: the active project, as resolved by
            ``Scripts/project_context.py``; else the folder above ``Scripts/``)
  --only    only study keys containing this substring (case-insensitive), the
            same filter ``run_harmonizers.py`` / ``run_reproducers.py`` use
  --force   overwrite existing *wrapper* files (never overwrites bespoke scripts
            that do not carry the "thin wrapper, generated" marker, unless --force
            is combined with --overwrite-bespoke, which is NOT recommended)
  --sb      also generate the Space-Bunny route wrappers
            (``<Key> - reproduction - SB.py``)
  --dry-run report what would be written, write nothing

The only files this ever writes are ``Datasets/<Key>/<Key> - reproduction.py``
(and, with ``--sb``, ``<Key> - reproduction - SB.py``).  An existing non-empty
script is left alone unless ``--force`` is given; a zero-byte one counts as
missing, because it cannot reproduce anything.

This module is also imported in-process by the CodingStudio app
(``routes_repro.py``): the packaged app has no Python interpreter of its own, and
the generator needs nothing beyond the standard library, so the app calls
:func:`generate` directly in a worker thread.  Keep it stdlib-only.
"""

import argparse
import os
import sys

WRAPPER_MARKER = "thin wrapper, generated"

TEMPLATE = '''# -*- coding: utf-8 -*-
"""Reproduction report for {key} (thin wrapper, generated).

Runs the shared reproduction engine ``Scripts/repro_lib.py::reproduce()``, which
prints the four-section report to stdout:

  (a) EXCLUSION CRITERIA -- ``{key} - exclusions.csv`` gates per DV;
  (b) ANALYSIS APPLIED   -- DV domains / veracities / timepoints from the sidecar;
  (c) RECALCULATION      -- per-domain N, mean true, mean false, d = mean(true) -
      mean(false) on the dv_*_01 (0-1 rescaled) scores, participant-level;
  (d) REPRODUCED VS NOT  -- recalc twins vs the eligible-primary contrasts coded in
      ``Extraction/{key}.json`` and the documented verdict in
      ``Reproduction/{key}.md``.

Nothing is written into ``Datasets/`` at runtime; intermediate work happens in
memory and the process temp dir is redirected to the root ``temp/``.
This wrapper is generated by ``Scripts/generate_repro_wrappers.py`` - do not hand-edit.
"""

import os
import sys

KEY = {key_repr}

HERE = os.path.dirname(os.path.abspath(__file__))      # .../Datasets/{key}
ROOT = os.path.dirname(os.path.dirname(HERE))          # project root (meta/)
for _p in (ROOT, os.path.join(ROOT, "Scripts")):
    if _p not in sys.path:
        sys.path.insert(0, _p)

if __name__ == "__main__":
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
        sys.stderr.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass
    from repro_lib import reproduce

    reproduce(KEY)
'''


def _is_wrapper(path):
    try:
        with open(path, encoding="utf-8") as fh:
            return WRAPPER_MARKER in fh.read()
    except Exception:
        return False


def _is_dataset_folder(dpath, name):
    """Only folders that look like study datasets get a wrapper."""
    return (os.path.isfile(os.path.join(dpath, name + " - harmonized_variables.csv"))
            or os.path.isfile(os.path.join(dpath, name + " - variables.csv"))
            or os.path.isfile(os.path.join(dpath, "harmonizer.py")))


def _write_new(path, content):
    """Write ``content`` to ``path`` via a sibling temp file + atomic replace, so a
    crash (or a concurrent reader such as ``run_reproducers.py``) never sees a
    half-written script."""
    tmp = path + ".tmp-generate"
    with open(tmp, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(content)
    os.replace(tmp, path)


def generate(root, force=False, sb=False, overwrite_bespoke=False, only=None,
             dry_run=False, out=None):
    """Create the missing wrappers under ``<root>/Datasets``.

    ``out`` receives each report line (default: ``print``), so the app can stream
    the output into its run log.  Returns 0 on success, 1 when there is no
    ``Datasets/`` folder.
    """
    if out is None:
        def out(line):
            print(line, flush=True)
    datasets_dir = os.path.join(root, "Datasets")
    if not os.path.isdir(datasets_dir):
        out(f"no Datasets dir at {datasets_dir}")
        return 1
    needle = (only or "").strip().lower()
    made = skipped = overwritten = 0
    for name in sorted(os.listdir(datasets_dir)):
        if needle and needle not in name.lower():
            continue
        dpath = os.path.join(datasets_dir, name)
        if not os.path.isdir(dpath) or not _is_dataset_folder(dpath, name):
            continue
        targets = [name + " - reproduction.py"]
        if sb:
            targets.append(name + " - reproduction - SB.py")
        for fname in targets:
            fpath = os.path.join(dpath, fname)
            exists = os.path.isfile(fpath) and os.path.getsize(fpath) > 0
            if exists:
                if not force:
                    skipped += 1
                    continue
                if not _is_wrapper(fpath) and not overwrite_bespoke:
                    out(f"skip bespoke (not a wrapper): {fpath}")
                    skipped += 1
                    continue
                overwritten += 1
            content = TEMPLATE.format(key=name, key_repr=repr(name))
            if dry_run:
                out(f"would generate {fpath}")
            else:
                _write_new(fpath, content)
                out(f"generated {fpath}")
            made += 1
    verb = "would generate" if dry_run else "generated"
    out(f"done: {verb}={made} overwritten={overwritten} skipped={skipped}"
        + (f" (filter: '{only}')" if needle else ""))
    return 0


def default_root():
    """The active project (``project_context``), else the folder above Scripts/."""
    here = os.path.dirname(os.path.abspath(__file__))
    if here not in sys.path:
        sys.path.insert(0, here)
    try:
        import project_context  # noqa: E402

        root = project_context.active_root()
        if root:
            return root
    except Exception:  # noqa: BLE001 - fall back to the layout guess
        pass
    return os.path.dirname(here)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--root", default=None, help="project root (default: the active project)")
    ap.add_argument("--only", default=None, metavar="SUBSTR",
                    help="only study keys containing this substring (case-insensitive)")
    ap.add_argument("--force", action="store_true", help="overwrite existing wrapper files")
    ap.add_argument("--sb", action="store_true", help="also generate SB-route wrappers")
    ap.add_argument("--overwrite-bespoke", action="store_true",
                    help="DANGEROUS: also overwrite bespoke (non-wrapper) reproduction scripts")
    ap.add_argument("--dry-run", action="store_true", help="report only, write nothing")
    args = ap.parse_args(argv)
    root = os.path.abspath(args.root or default_root())
    return generate(root, force=args.force, sb=args.sb,
                    overwrite_bespoke=args.overwrite_bespoke, only=args.only,
                    dry_run=args.dry_run)


if __name__ == "__main__":
    sys.exit(main())
