"""Write ``Results/field_instructions.md`` - the scheme's per-field instructions.

The scheme carries two prose slots per field: ``description`` (what the field
is) and ``instruction`` (how to code it and where to look in the paper).  The
instructions come from :mod:`scheme_instructions`, which transcribes the
campaign's own coding prompt (the MM, SB and marking instruction documents and
the corresponding-author rules in ``AGENTS.md``).

This script renders the table an agent or a reviewer can read: every field,
its instruction, and the source passage the instruction was taken from.

    python Scripts/build_field_instructions_report.py

The product lands in ``Results/field_instructions.md``; the script writes
nothing else.
"""

from __future__ import annotations

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
if HERE not in sys.path:
    sys.path.insert(0, HERE)

import scheme_instructions as SI  # noqa: E402
import scheme_lib as SL  # noqa: E402

#: Where the report goes.
REPORT_PATH = os.path.join(REPO, "Results", "field_instructions.md")

#: The legacy schema, used to read the scheme's field order.
LEGACY_SCHEMA = os.path.join(HERE, "coding_web", "schema.json")


def _load_scheme():
    """The active scheme, normalised."""
    import project_context as pc
    return pc.scheme()


def _escape(text):
    """A table cell: no pipes, no newlines."""
    return " ".join((text or "").split()).replace("|", "\\|")


def _rows(fields, source_of=True):
    """The markdown rows of a field table."""
    rows = []
    for field in fields:
        name = field["name"]
        instruction = field.get("instruction") or ""
        cells = ["`%s`" % name, _escape(instruction)]
        if source_of:
            cells.append(SI.SOURCE_OF.get(name, "-"))
        rows.append("| " + " | ".join(cells) + " |")
    return rows


def _header(source_of=True):
    if source_of:
        return ("| field | instruction | source |\n"
                "|---|---|---|")
    return "| field | instruction |\n|---|---|"


def build(scheme=None):
    """The report as a string."""
    scheme = scheme if scheme is not None else _load_scheme()
    fields = SL.all_fields(scheme)
    study = [f for f in fields if f.get("scope") == "study"]
    metric = [f for f in fields if f.get("scope") == "metric"]
    modules = scheme.get("modules") or {}

    instructed = [f for f in fields if (f.get("instruction") or "").strip()]

    out = []
    out.append("# Field instructions")
    out.append("")
    out.append("Every field of the coding scheme carries two prose slots: a")
    out.append("**description** (what the field is) and an **instruction** (how")
    out.append("to code it and where to look in the paper).  The instructions")
    out.append("are the campaign's own coding rules, transcribed from the")
    out.append("documents the coding agents were given - they are not a fresh")
    out.append("description of the field.")
    out.append("")
    out.append("**%d of %d fields carry an instruction.**  The table below is"
               % (len(instructed), len(fields)))
    out.append("generated by `python Scripts/build_field_instructions_report.py`")
    out.append("from `Scripts/scheme_instructions.py`.")
    out.append("")

    # -- the source passages ------------------------------------------------
    out.append("## Where the instructions come from")
    out.append("")
    out.append("Each instruction is transcribed from one passage of one")
    out.append("source document.  The `source` column of the tables below")
    out.append("refers to these keys.")
    out.append("")
    out.append("| key | document | heading | lines | what the passage carries |")
    out.append("|---|---|---|---|---|")
    for key in sorted(SI.SOURCES):
        document, heading, first, last, note = SI.SOURCES[key]
        out.append("| `%s` | `%s` | %s | %d-%d | %s |"
                   % (key, document, heading, first, last, note))
    out.append("")
    out.append("The line numbers refer to the documents as they stand in the")
    out.append("campaign checkout (`Scripts/MM_CODING_INSTRUCTIONS.md`,")
    out.append("`Scripts/SB_CODING_INSTRUCTIONS.md`,")
    out.append("`Scripts/MARKING_CODING_INSTRUCTIONS.md`, `AGENTS.md`).")
    out.append("")

    # -- study fields -------------------------------------------------------
    out.append("## Study fields (%d)" % len(study))
    out.append("")
    out.append(_header())
    out.extend(_rows(study))
    out.append("")

    # -- metric fields ------------------------------------------------------
    out.append("## Metric (per-contrast) fields (%d)" % len(metric))
    out.append("")
    out.append("The effect routes, the contrast rules, the `dv_polarity`")
    out.append("meaning and the timepoint rules are attached to the metric")
    out.append("fields they are about.")
    out.append("")
    out.append(_header())
    out.extend(_rows(metric))
    out.append("")

    # -- module fields ------------------------------------------------------
    out.append("## Intervention-module fields (%d)" % sum(
        len(mod.get("fields") or []) for mod in modules.values()))
    out.append("")
    out.append("A module field is coded only when its module applies to the")
    out.append("record's `Intervention_Type`.")
    out.append("")
    for key, mod in modules.items():
        mod_fields = mod.get("fields") or []
        if not mod_fields:
            continue
        out.append("### %s (%d fields)"
                   % (mod.get("label") or key, len(mod_fields)))
        out.append("")
        out.append(_header())
        out.extend(_rows(mod_fields))
        out.append("")

    return "\n".join(out) + "\n"


def main():
    report = build()
    os.makedirs(os.path.dirname(REPORT_PATH), exist_ok=True)
    with open(REPORT_PATH, "w", encoding="utf-8") as handle:
        handle.write(report)
    print("wrote %s (%d characters)" % (REPORT_PATH, len(report)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
